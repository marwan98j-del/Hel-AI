TRANSLATIONS = {
    "en": EN,
    "ckb": CKB,
    "ar": AR,
}


def normalize_language(value) -> str | None:
    value = str(value or "").strip().lower()
    return value if value in TRANSLATIONS else None


def resolve_language(session_choice=None, profile_preference=None) -> str:
    """session_state choice -> profile's saved preference -> Kurdish Sorani."""
    chosen = normalize_language(session_choice)
    if chosen:
        return chosen
    saved = PROFILE_LANGUAGE_MAP.get(str(profile_preference or "").strip().lower())
    return saved or DEFAULT_LANGUAGE


def select_language(session_state, query_lang=None, profile=None) -> str:
    """Resolve and store this run's language in a Streamlit-like session dict.

    A ``?lang=`` URL value counts as an explicit choice the first time the
    session sees it, so a refreshed or shared link keeps its language.
    """
    if CHOICE_KEY not in session_state and normalize_language(query_lang):
        session_state[CHOICE_KEY] = normalize_language(query_lang)
    lang = resolve_language(
        session_state.get(CHOICE_KEY),
        (profile or {}).get("preferred_language"),
    )
    session_state[ACTIVE_KEY] = lang
    return lang


def active_language() -> str:
    """Language of the current Streamlit session; the default outside a run."""
    try:
        from streamlit.runtime.scriptrunner import get_script_run_ctx

        if get_script_run_ctx(suppress_warning=True) is None:
            return DEFAULT_LANGUAGE
        import streamlit as st

        return normalize_language(st.session_state.get(ACTIVE_KEY)) or DEFAULT_LANGUAGE
    except Exception:
        return DEFAULT_LANGUAGE


def is_rtl(lang: str | None = None) -> bool:
    return (lang or active_language()) in RTL_LANGUAGES


def t(key: str, lang: str | None = None, **kwargs) -> str:
    """Translate ``key``; missing keys fall back to English, then to the key."""
    lang = normalize_language(lang) or active_language()
    template = TRANSLATIONS.get(lang, {}).get(key)
    if template is None:
        template = EN.get(key, key)
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template


def t_value(prefix: str, value, lang: str | None = None) -> str:
    """Display label for a stored English value; unknown values pass through."""
    text = str(value if value is not None else "")
    key = f"{prefix}.{text}"
    if key not in EN:
        return text
    return t(key, lang=lang)


def localize_digits(value, lang: str | None = None) -> str:
    text = str(value)
    if (lang or active_language()) in RTL_LANGUAGES:
        return text.translate(EASTERN_ARABIC_DIGITS)
    return text


def format_number(value, lang: str | None = None) -> str:
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    return localize_digits(value, lang)


def format_percent(value, lang: str | None = None) -> str:
    lang = lang or active_language()
    number = format_number(value, lang)
    if lang in RTL_LANGUAGES:
        return f"٪{number}"
    return f"{number}%"


def format_date(value, lang: str | None = None) -> str:
    """'31 OCT 2026' in English, '٣١ تشرینی یەکەم ٢٠٢٦' in Kurdish/Arabic."""
    lang = lang or active_language()
    if isinstance(value, datetime):
        parsed = value.date()
    elif isinstance(value, date):
        parsed = value
    else:
        text = str(value or "").strip()
        if not text:
            return t("common.not_stated", lang=lang)
        try:
            parsed = date.fromisoformat(text[:10])
        except ValueError:
            return text
    months = MONTHS.get(lang, MONTHS[FALLBACK_LANGUAGE])
    day = f"{parsed.day:02d}" if lang == "en" else str(parsed.day)
    return localize_digits(f"{day} {months[parsed.month - 1]} {parsed.year}", lang)


def count_phrase(count: int, lang: str | None = None) -> tuple[str, str]:
    """(headline template, count phrase) with each language's plural rules.

    The headline template has a ``{count}`` slot for the highlighted phrase.
    """
    lang = normalize_language(lang) or active_language()
    if count <= 0:
        return t("hero.headline_zero", lang=lang), ""
    if count == 1:
        return t("hero.headline_one", lang=lang), t("hero.count_one", lang=lang)
    if count == 2:
        return t("hero.headline_two", lang=lang), t("hero.count_two", lang=lang)
    if count <= 10:
        number = t(f"number.{count}", lang=lang)
        return t("hero.headline_many", lang=lang), t("hero.count_few", lang=lang, n=number)
    return (
        t("hero.headline_many", lang=lang),
        t("hero.count_many", lang=lang, n=format_number(count, lang)),
    )


BOOSTER_PATTERNS = (
    (r"^Reach (.+) level$", "booster.reach_level", "level"),
    (r"^Reach a ([\d.]+)% academic average$", "booster.reach_average", "pct"),
    (r"^Build ([\d.]+) years of work experience$", "booster.build_years", "years"),
)


def translate_booster_label(label, lang: str | None = None) -> str:
    """Display-layer translation of matcher.analyze_improvements labels."""
    import re

    lang = normalize_language(lang) or active_language()
    text = str(label or "")
    if f"booster_label.{text}" in EN:
        return t(f"booster_label.{text}", lang=lang)
    for pattern, key, field in BOOSTER_PATTERNS:
        found = re.match(pattern, text)
        if not found:
            continue
        value = found.group(1)
        if field == "level":
            value = t_value("education", value, lang)
        elif field == "pct":
            value = format_percent(float(value), lang)
        else:
            value = format_number(float(value), lang)
        return t(key, lang=lang, **{field: value})
    return text


